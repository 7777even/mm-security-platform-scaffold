/** 后台管理端菜单数据：对齐八大一级子系统 + 二/三级菜单与列表字段（迁移自 ui-redesign pcMenus） */

export type MgmtCell = string | { text: string; type: 'ok' | 'warn' | 'bad' };

export type MgmtTab = {
  name: string;
  columns: string[];
  rows: MgmtCell[][];
};

export type MgmtMenuLeaf = {
  name: string;
  path: string;
  icon: string;
  columns: string[];
  rows: MgmtCell[][];
  /** 面包屑中间段，如「台账」「运行监控」 */
  folder?: string;
  action?: string;
  filters?: string[];
  searchPlaceholder?: string;
  /** 页内二级 Tab（监控页、水系统等） */
  tabs?: MgmtTab[];
  /** 表单型页面（无列表） */
  pageType?: 'table' | 'form';
  formFields?: { label: string; value: string }[];
};

export type MgmtMenuFolder = {
  name: string;
  icon: string;
  children: MgmtMenuLeaf[];
};

export type MgmtChild = MgmtMenuLeaf | MgmtMenuFolder;

export type MgmtMenuGroup = {
  title: string;
  icon: string;
  key: string;
  children: MgmtMenuLeaf[];
};

type MgmtGroupRaw = {
  title: string;
  icon: string;
  key: string;
  children: MgmtChild[];
};

export function isMgmtFolder(c: MgmtChild): c is MgmtMenuFolder {
  return Array.isArray((c as MgmtMenuFolder).children) && !(c as MgmtMenuLeaf).path;
}

export function flattenLeaves(children: MgmtChild[]): MgmtMenuLeaf[] {
  return children.flatMap((c) => (isMgmtFolder(c) ? c.children : [c]));
}

export function firstLeafPath(g: MgmtMenuGroup): string {
  const leaves = flattenLeaves(g.children);
  return leaves[0]?.path || '/workbench';
}

export function leafCount(g: MgmtMenuGroup): number {
  return flattenLeaves(g.children).length;
}

function ok(t: string): MgmtCell {
  return { text: t, type: 'ok' };
}
function warn(t: string): MgmtCell {
  return { text: t, type: 'warn' };
}
function bad(t: string): MgmtCell {
  return { text: t, type: 'bad' };
}

function L(
  name: string,
  path: string,
  icon: string,
  columns: string[],
  rows: MgmtCell[][],
  extra: Partial<MgmtMenuLeaf> = {},
): MgmtMenuLeaf {
  return { name, path, icon, columns, rows, pageType: 'table', ...extra };
}

function facility(
  slug: string,
  name: string,
  columns: string[],
  row: MgmtCell[],
  icon = 'box',
): MgmtMenuLeaf {
  return L(
    name,
    `/${slug}`,
    icon,
    columns,
    [row, row.map((c, i) => (i === 0 && typeof c === 'string' ? c.replace(/01|001/, '02') : c))],
    {
      folder: '台账',
      action: '新增设施',
      searchPlaceholder: '搜索设施编号 / 名称',
      filters: ['运行状态：全部', '启用：全部'],
    },
  );
}

